"use client";

import { useEffect, useRef, useState } from "react";

// Account settings.
//
// The registered email (the login) is shown read-only and is deliberately NOT
// the alert address: people sign up with an admin mailbox but want alerts in a
// dispatch inbox. It seeds the alert field on first open and is otherwise left
// alone. Every alert address carries its own alert/remind flags so a customer
// can hear that a load is late without receiving internal check-in nags.
export default function Settings({ profile, onClose, onSaved }) {
  const registeredEmail = profile?.email || "";
  const [notifyEmail, setNotifyEmail] = useState(
    profile?.notify_email || registeredEmail || ""
  );
  const [notifyAlert, setNotifyAlert] = useState(profile?.notify_alert !== false);
  const [notifyRemind, setNotifyRemind] = useState(profile?.notify_remind !== false);
  const [cc1, setCc1] = useState({
    email: profile?.cc1_email || "",
    alert: profile?.cc1_alert !== false,
    remind: !!profile?.cc1_remind,
  });
  const [cc2, setCc2] = useState({
    email: profile?.cc2_email || "",
    alert: profile?.cc2_alert !== false,
    remind: !!profile?.cc2_remind,
  });
  const [fullName, setFullName] = useState(profile?.full_name || "");
  const [phone, setPhone] = useState(profile?.phone || "");
  const [checkinDefault, setCheckinDefault] = useState(!!profile?.checkin_email_default);
  const [samsaraToken, setSamsaraToken] = useState("");
  const [telegramConnected, setTelegramConnected] = useState(!!profile?.telegram_chat_id);
  const [telegramUrl, setTelegramUrl] = useState("");
  const [telegramBusy, setTelegramBusy] = useState(false);
  const [telegramMessage, setTelegramMessage] = useState("");
  const [waitingForTelegram, setWaitingForTelegram] = useState(false);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  // Set by every field. Once the user has typed anything, a click on the
  // backdrop stops dismissing the dialog and warns instead — losing a half-typed
  // recipient list to a stray click just outside the panel is a bad trade for
  // the convenience of click-outside-to-close.
  const [dirty, setDirty] = useState(false);
  const [warnUnsaved, setWarnUnsaved] = useState(false);
  const onSavedRef = useRef(onSaved);
  onSavedRef.current = onSaved;

  useEffect(() => {
    if (!waitingForTelegram) return;
    const timer = setInterval(async () => {
      try {
        const result = await fetch("/api/telegram/link", { cache: "no-store" }).then((r) => r.json());
        if (result.connected) {
          setTelegramConnected(true);
          setWaitingForTelegram(false);
          setTelegramMessage("Telegram is connected.");
          await onSavedRef.current?.();
        } else if (result.error) {
          setTelegramMessage(`Telegram status check failed: ${result.error}`);
        } else if (result.lastError) {
          setTelegramMessage(`Telegram cannot reach the webhook: ${result.lastError}`);
        } else if (result.webhookUrl !== result.expectedUrl) {
          setTelegramMessage(
            `Webhook URL mismatch. Expected ${result.expectedUrl}; Telegram has ${result.webhookUrl || "no webhook"}. Set NEXT_PUBLIC_APP_URL to your live TruckOn URL in Vercel and redeploy.`
          );
        } else if (!result.callbackUpdatesEnabled) {
          setTelegramMessage("Telegram button updates are not enabled yet. Click Connect Telegram again to refresh the bot webhook, then open the new link and press Start.");
        } else {
          setTelegramMessage(
            "Waiting for the one-time link code. Open the link generated by TruckOn Settings and press Start; a plain /start will not connect the account."
          );
        }
      } catch {
        // Keep polling; closing this dialog also stops the interval.
      }
    }, 3000);
    return () => clearInterval(timer);
  }, [waitingForTelegram]);

  async function connectTelegram() {
    setTelegramBusy(true);
    setTelegramMessage("");
    try {
      const result = await fetch("/api/telegram/link", { method: "POST" }).then((r) => r.json());
      if (result.error) throw new Error(result.error);
      setTelegramUrl(result.url);
      setWaitingForTelegram(true);
      setTelegramMessage(
        "Open this link and press Start in Telegram. Do not send /start manually; the link contains the account connection code."
      );
    } catch (e) {
      setTelegramMessage(e.message || "Could not connect Telegram.");
    } finally {
      setTelegramBusy(false);
    }
  }

  async function repairTelegram() {
    setTelegramBusy(true);
    setTelegramMessage("");
    try {
      const result = await fetch("/api/telegram/link", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ action: "repair" }),
      }).then((r) => r.json());
      if (result.error) throw new Error(result.error);
      setTelegramMessage("Bot webhook refreshed. Return to Telegram and press Update now again.");
    } catch (e) {
      setTelegramMessage(e.message || "Could not refresh the Telegram webhook.");
    } finally {
      setTelegramBusy(false);
    }
  }

  async function disconnectTelegram() {
    setTelegramBusy(true);
    setTelegramMessage("");
    try {
      const result = await fetch("/api/telegram/link", { method: "DELETE" }).then((r) => r.json());
      if (result.error) throw new Error(result.error);
      setTelegramConnected(false);
      setTelegramUrl("");
      setWaitingForTelegram(false);
      setTelegramMessage("Telegram disconnected.");
      await onSaved?.();
    } catch (e) {
      setTelegramMessage(e.message || "Could not disconnect Telegram.");
    } finally {
      setTelegramBusy(false);
    }
  }

  function requestClose() {
    if (!dirty) return onClose?.();
    setWarnUnsaved(true);
  }

  async function submit(e) {
    e.preventDefault();
    if (!notifyEmail.trim()) {
      setError("An alert email is required — that's where alerts go.");
      return;
    }
    setBusy(true);
    setError("");
    try {
      const body = {
        notify_email: notifyEmail.trim(),
        notify_alert: notifyAlert,
        notify_remind: notifyRemind,
        cc1_email: cc1.email.trim() || null,
        cc1_alert: cc1.alert,
        cc1_remind: cc1.remind,
        cc2_email: cc2.email.trim() || null,
        cc2_alert: cc2.alert,
        cc2_remind: cc2.remind,
        full_name: fullName.trim() || null,
        phone: phone.trim() || null,
        checkin_email_default: checkinDefault,
      };
      // Only send the token when the user actually typed one, so leaving the
      // field blank never wipes a token they already have stored.
      if (samsaraToken.trim()) body.samsara_token = samsaraToken.trim();

      const res = await fetch("/api/profile", {
        method: "PUT",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(body),
      }).then((r) => r.json());

      if (res.error) {
        setError(res.error);
        return;
      }
      await onSaved?.();
      onClose?.();
    } catch (err) {
      setError(err.message || "Couldn't save.");
    } finally {
      setBusy(false);
    }
  }

  return (
    <div className="modal-backdrop" onClick={requestClose}>
      {/* autoComplete="off" on the form and every field: Chrome was dropping the
          account email into the Phone box (it skips the disabled registered-email
          input and fills the next text field it likes), and that guess would have
          been saved as the user's phone number on the next Save. */}
      <form
        className="modal"
        autoComplete="off"
        onClick={(e) => e.stopPropagation()}
        // One listener on the form rather than touching every field: input
        // events bubble, so any edit anywhere marks the dialog dirty.
        onInput={() => {
          setDirty(true);
          setWarnUnsaved(false);
        }}
        onSubmit={submit}
      >
        <h2 className="modal-title">Settings</h2>

        <label className="auth-label">Registered email</label>
        <input className="auth-input" type="email" value={registeredEmail} disabled readOnly />
        <p className="field-hint">
          Your sign-in address. Alerts don&rsquo;t have to go here — set the alert
          email below.
        </p>

        <label className="auth-label" htmlFor="ne">
          Alert email <span className="req">*</span>
        </label>
        <input
          id="ne"
          autoComplete="off"
          className="auth-input"
          type="email"
          value={notifyEmail}
          onChange={(e) => setNotifyEmail(e.target.value)}
          required
        />
        <MailFlags
          idPrefix="own"
          alert={notifyAlert}
          remind={notifyRemind}
          onAlert={setNotifyAlert}
          onRemind={setNotifyRemind}
        />

        <label className="auth-label" htmlFor="cc1">
          Also email <span className="opt">optional</span>
        </label>
        <input
          id="cc1"
          autoComplete="off"
          className="auth-input"
          type="email"
          placeholder="name@company.com"
          value={cc1.email}
          onChange={(e) => setCc1({ ...cc1, email: e.target.value })}
        />
        <MailFlags
          idPrefix="cc1"
          disabled={!cc1.email.trim()}
          alert={cc1.alert}
          remind={cc1.remind}
          onAlert={(v) => setCc1({ ...cc1, alert: v })}
          onRemind={(v) => setCc1({ ...cc1, remind: v })}
        />

        <label className="auth-label" htmlFor="cc2">
          Also email <span className="opt">optional</span>
        </label>
        <input
          id="cc2"
          autoComplete="off"
          className="auth-input"
          type="email"
          placeholder="name@company.com"
          value={cc2.email}
          onChange={(e) => setCc2({ ...cc2, email: e.target.value })}
        />
        <MailFlags
          idPrefix="cc2"
          disabled={!cc2.email.trim()}
          alert={cc2.alert}
          remind={cc2.remind}
          onAlert={(v) => setCc2({ ...cc2, alert: v })}
          onRemind={(v) => setCc2({ ...cc2, remind: v })}
        />
        <p className="field-hint">
          You can add your customer, carrier, and/or driver&rsquo;s email
          addresses too. Each address gets its own copy, so nobody sees the
          others&rsquo; email.
        </p>

        <h3 className="section-head">User info</h3>

        <label className="auth-label" htmlFor="fn">
          Your name <span className="opt">(optional)</span>
        </label>
        <input
          id="fn"
          autoComplete="off"
          className="auth-input"
          value={fullName}
          onChange={(e) => setFullName(e.target.value)}
        />

        <label className="auth-label" htmlFor="ph">
          Phone <span className="opt">(optional)</span>
        </label>
        {/* autoComplete="tel" rather than "off": Chrome ignores "off" on contact
            fields and was filling this with the account email. Naming the field
            honestly makes it offer a phone number instead of guessing. The API
            also rejects an address here, since no attribute is a guarantee. */}
        <input
          id="ph"
          autoComplete="tel"
          inputMode="tel"
          type="tel"
          className="auth-input"
          value={phone}
          onChange={(e) => setPhone(e.target.value)}
        />

        <label className="auth-label" htmlFor="st">
          Samsara API token <span className="opt">optional</span>
        </label>
        <input
          id="st"
          autoComplete="off"
          className="auth-input"
          type="password"
          placeholder={profile?.has_samsara_token ? "•••••••• already saved" : "only needed for truck # tracking"}
          value={samsaraToken}
          onChange={(e) => setSamsaraToken(e.target.value)}
        />
        <p className="field-hint">
          Only needed if you want to type a <b>truck number</b> instead of pasting
          a Samsara Live Share link. It comes from your own Samsara account
          (Settings → API Tokens) and lets us read that fleet&rsquo;s live GPS.
          Stored encrypted. Motive truck numbers can also be entered in the load
          source as <b>Motive: 123</b> when the app owner has configured
          <code> MOTIVE_API </code> in Vercel.
        </p>

        <h3 className="section-head">Telegram alerts</h3>
        <p className="field-hint">
          Connect Telegram, then choose how often each load sends a status and
          location update. Late and arrival changes also send an immediate message.
        </p>
        <div className="modal-actions">
          <span>{telegramConnected ? "Telegram connected" : "Telegram not connected"}</span>
          {telegramConnected ? (
            <>
              <button
                type="button"
                className="btn secondary"
                onClick={repairTelegram}
                disabled={telegramBusy}
              >
                {telegramBusy ? "Refreshing…" : "Refresh bot"}
              </button>
              <button
                type="button"
                className="btn secondary"
                onClick={disconnectTelegram}
                disabled={telegramBusy}
              >
                {telegramBusy ? "Please wait…" : "Disconnect"}
              </button>
            </>
          ) : (
            <button
              type="button"
              className="btn secondary"
              onClick={connectTelegram}
              disabled={telegramBusy}
            >
              {telegramBusy ? "Connecting…" : "Connect Telegram"}
            </button>
          )}
        </div>
        {telegramUrl ? (
          <p className="field-hint">
            <a href={telegramUrl} target="_blank" rel="noreferrer">
              Open your TruckOn Telegram bot
            </a>
          </p>
        ) : null}
        {telegramMessage ? <p className="field-hint">{telegramMessage}</p> : null}

        <label className="check-row">
          <input
            type="checkbox"
            checked={checkinDefault}
            onChange={(e) => setCheckinDefault(e.target.checked)}
          />
          <span>Tick &ldquo;remind&rdquo; by default on new rows</span>
        </label>

        {error ? <p className="auth-error">{error}</p> : null}
        {warnUnsaved ? (
          <p className="auth-error">
            You have unsaved changes — press <b>Save settings</b>, or{" "}
            <b>Cancel</b> to discard them.
          </p>
        ) : null}

        <div className="modal-actions">
          <button type="button" className="btn secondary" onClick={onClose} disabled={busy}>
            Cancel
          </button>
          <button className="btn" disabled={busy}>
            {busy ? "Saving…" : "Save settings"}
          </button>
        </div>
      </form>
    </div>
  );
}

// The two per-address switches. Wording matches the table's column exactly, so
// "alert" and "remind" mean the same thing in both places.
function MailFlags({ idPrefix, alert, remind, onAlert, onRemind, disabled = false }) {
  return (
    <div className={"mail-flags" + (disabled ? " disabled" : "")}>
      <label title="Alert if the ETA runs past the deadline">
        <input
          type="checkbox"
          id={`${idPrefix}-alert`}
          checked={alert && !disabled}
          disabled={disabled}
          onChange={(e) => onAlert(e.target.checked)}
        />
        <span>alert</span>
      </label>
      <label title="Remind 5 minutes before the delivery appointment">
        <input
          type="checkbox"
          id={`${idPrefix}-remind`}
          checked={remind && !disabled}
          disabled={disabled}
          onChange={(e) => onRemind(e.target.checked)}
        />
        <span>remind</span>
      </label>
    </div>
  );
}
